import { rows } from './rows.js';

const format = 'recall-deck.backup';
const version = 1;
const tables = {
  decks: ['id', 'name', 'parentId', 'color'],
  cards: ['id', 'deckId', 'front', 'back', 'expected', 'reviewState', 'reviewStep', 'dueAt', 'studySelected'],
  reviews: ['rowid', 'attemptId', 'cardId', 'answer', 'rating', 'reviewedAt', 'source'],
  study_events: ['id', 'cardId', 'occurredAt', 'selected', 'rating'],
  study_attempt_details: ['attemptId', 'eventId', 'previousReviewStep', 'previousDueAt'],
};

export function takeBackup(db) {
  return db.transaction(() => ({
    format,
    version,
    tables: Object.fromEntries(Object.entries(tables).map(([table, columns]) => [
      table, rows(db, `SELECT ${columns.join(', ')} FROM ${table} ORDER BY rowid`)
        .map(row => columns.map(column => row[column])),
    ])),
    sequence: rows(db, "SELECT name, seq FROM sqlite_sequence WHERE name IN ('decks', 'cards') ORDER BY name")
      .map(({ name, seq }) => [name, seq]),
  })).immediate();
}

const rating = value => ['known', 'fuzzy', 'forgotten'].includes(value);
const nullable = check => value => value === null || check(value);
const string = value => typeof value === 'string';
const id = value => Number.isSafeInteger(value) && value > 0;
const timestamp = value => Number.isSafeInteger(value) && Math.abs(value) <= 8.64e15;
const step = value => Number.isInteger(value) && value >= 0 && value <= 6;
const bit = value => value === 0 || value === 1;
const source = value => value === 'study' || value === 'test';
const checks = {
  decks: [id, string, nullable(id), nullable(string)],
  cards: [id, id, string, string, string, nullable(rating), step, nullable(timestamp), bit],
  reviews: [id, string, nullable(id), string, rating, timestamp, source],
  study_events: [id, id, timestamp, nullable(bit), nullable(rating)],
  study_attempt_details: [string, id, step, nullable(timestamp)],
};

function validRows(data, fields) {
  return Array.isArray(data) && data.every(row => Array.isArray(row) && row.length === fields.length
    && fields.every((check, index) => check(row[index])));
}

export function validateBackup(backup) {
  if (backup?.format !== format || backup.version !== version) {
    throw new Error('备份格式或版本不受支持。');
  }
  if (!Object.entries(checks).every(([table, fields]) => validRows(backup.tables?.[table], fields)) ||
    !validRows(backup.sequence, [value => value === 'decks' || value === 'cards', value => value === 0 || id(value)])) {
    throw new Error('备份内容不完整或包含无效数据。');
  }
  const decks = new Map(backup.tables.decks.map(([id, , parentId]) => [id, parentId]));
  if (![...decks.values()].includes(null) || [...decks.values()].some(parent => parent !== null && decks.get(parent) !== null)) {
    throw new Error('备份中的卡组层级无效。');
  }
  const sequence = new Map(backup.sequence);
  if (sequence.size !== backup.sequence.length ||
    backup.tables.decks.some(([id]) => id > (sequence.get('decks') ?? 0)) ||
    [...backup.tables.cards.map(([id]) => id), ...backup.tables.study_events.map(([, id]) => id)]
      .some(id => id > (sequence.get('cards') ?? 0))) {
    throw new Error('备份中的编号记录无效。');
  }
  return backup;
}

export function restoreBackup(db, backup, originalToken) {
  validateBackup(backup);
  db.transaction(() => {
    // data_version detects another process writing after the safety copy was taken.
    if (originalToken && backupToken(db) !== originalToken) {
      throw new Error('卡库在备份后发生了变化，请重新开始恢复。');
    }
    db.exec('PRAGMA defer_foreign_keys = ON');
    db.exec('DELETE FROM study_attempt_details; DELETE FROM reviews; DELETE FROM cards; DELETE FROM decks;');
    try {
      for (const [table, columns] of Object.entries(tables)) {
        if (table === 'study_events') db.exec('DELETE FROM study_events'); // Discard events generated by card triggers.
        const placeholders = columns.map(() => '?').join(', ');
        const statement = db.prepare(`INSERT INTO ${table} (${columns.join(', ')}) VALUES (${placeholders})`);
        try {
          for (const values of backup.tables[table]) statement.all(...values);
        } finally {
          statement.finalize();
        }
      }
      if (rows(db, 'PRAGMA foreign_key_check').length) throw new Error('外键检查失败');
      db.exec("DELETE FROM sqlite_sequence WHERE name IN ('decks', 'cards')");
      for (const sequence of backup.sequence) rows(db, 'INSERT INTO sqlite_sequence (name, seq) VALUES (?, ?)', ...sequence);
    } catch {
      throw new Error('备份中的记录发生冲突或引用了缺失的内容。恢复已取消。');
    }
  }).immediate();
}

export function backupToken(db) {
  return `${rows(db, 'PRAGMA data_version')[0].data_version}:${rows(db, 'SELECT total_changes() AS changes')[0].changes}`;
}
